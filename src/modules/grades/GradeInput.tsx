import React, { useState, useEffect } from 'react';
import {
  GraduationCap,
  Save,
  Printer,
  Search,
  Sparkles,
  HelpCircle,
  AlertCircle,
  CheckCircle2,
  BookOpen,
} from 'lucide-react';
import { useAuth } from '../../contexts/AuthContext';
import { useSchool } from '../../contexts/SchoolContext';
import { useNotification } from '../../contexts/NotificationContext';
import {
  getFirestoreStudents,
  getFirestoreGrades,
  saveBatchFirestoreGrades,
  logAuditEvent,
} from '../../services/firebase/firestoreService';
import { syncGradesToSheets } from '../../services/sync/syncManager';
import { Student, GradeRecord, AssessmentType } from '../../types';
import { generateCompetencyDescription } from '../../utils/calculations';
import { formatDateIndo } from '../../utils/formatters';

export const GradeInput: React.FC = () => {
  const { user, isAdmin, isTeacher, canAccessClass } = useAuth();
  const { schoolProfile, subjects } = useSchool();
  const { showToast } = useNotification();

  const [selectedClass, setSelectedClass] = useState<string>(() => {
    if (isTeacher && user && user.assignedClasses.length > 0) {
      return user.assignedClasses[0];
    }
    return '1';
  });

  const [selectedSubject, setSelectedSubject] = useState<string>(subjects[0]?.name || 'Matematika');
  const [selectedAssessmentType, setSelectedAssessmentType] = useState<AssessmentType>('Sumatif Lingkup Materi');
  const [materialScope, setMaterialScope] = useState<string>('Bab 1 / Lingkup Materi 1');
  const [selectedSemester, setSelectedSemester] = useState<'1' | '2'>(schoolProfile?.activeSemester || '1');

  const [students, setStudents] = useState<Student[]>([]);
  const [scoresMap, setScoresMap] = useState<Record<string, { score: string; description: string }>>({});
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [searchTerm, setSearchTerm] = useState('');

  // Load students & existing grades
  useEffect(() => {
    async function loadData() {
      setLoading(true);
      try {
        const studentList = await getFirestoreStudents(selectedClass);
        const active = studentList.filter(s => s.status === 'Aktif');
        setStudents(active);

        const existingGrades = await getFirestoreGrades(selectedClass, selectedSubject, selectedSemester);
        // Filter by assessment type and material scope
        const matched = existingGrades.filter(g =>
          g.assessmentType === selectedAssessmentType &&
          g.material.toLowerCase() === materialScope.toLowerCase()
        );

        const map: Record<string, { score: string; description: string }> = {};
        active.forEach(s => {
          const found = matched.find(g => g.studentId === s.studentId);
          map[s.studentId] = {
            score: found && found.score !== null ? String(found.score) : '',
            description: found ? (found.description || '') : '',
          };
        });

        setScoresMap(map);
      } catch (e: any) {
        showToast('error', 'Gagal Memuat Nilai', e.message);
      } finally {
        setLoading(false);
      }
    }

    if (canAccessClass(selectedClass)) {
      loadData();
    }
  }, [selectedClass, selectedSubject, selectedAssessmentType, materialScope, selectedSemester]);

  const handleScoreChange = (studentId: string, val: string) => {
    // Only allow numbers 0-100 or empty
    if (val !== '') {
      const num = Number(val);
      if (isNaN(num) || num < 0 || num > 100) return;
    }

    setScoresMap(prev => ({
      ...prev,
      [studentId]: {
        ...(prev[studentId] || { description: '' }),
        score: val,
      },
    }));
  };

  const handleDescriptionChange = (studentId: string, val: string) => {
    setScoresMap(prev => ({
      ...prev,
      [studentId]: {
        ...(prev[studentId] || { score: '' }),
        description: val,
      },
    }));
  };

  // Generate automated competency descriptions for all filled scores
  const handleAutoGenerateDescriptions = () => {
    const updated = { ...scoresMap };
    let count = 0;
    students.forEach(s => {
      const entry = updated[s.studentId];
      if (entry && entry.score !== '') {
        const num = Number(entry.score);
        entry.description = generateCompetencyDescription(s.name, selectedSubject, num);
        count++;
      }
    });
    setScoresMap(updated);
    showToast('info', 'Deskripsi Dihasilkan', `Deskripsi capaian dibuat otomatis untuk ${count} siswa.`);
  };

  // Save all grades
  const handleSaveGrades = async () => {
    if (!canAccessClass(selectedClass)) {
      showToast('error', 'Akses Ditolak', 'Anda tidak berwenang mengelola kelas ini.');
      return;
    }

    setSaving(true);
    try {
      const schoolYear = schoolProfile?.academicYear || '2026/2027';
      const recordsToSave: GradeRecord[] = [];

      students.forEach(s => {
        const entry = scoresMap[s.studentId];
        const rawScore = entry?.score?.trim();
        const scoreVal = rawScore !== '' && rawScore !== undefined ? Number(rawScore) : null;

        // Unique document ID: GRD-{Tahun}-{Sem}-{Kelas}-{MataPelajaran}-{JenisAsesmen}-{Materi}-{ID_Siswa}
        const safeSubject = selectedSubject.replace(/\s+/g, '_');
        const safeType = selectedAssessmentType.replace(/\s+/g, '_');
        const safeMat = materialScope.replace(/\s+/g, '_');
        const gradeId = `GRD-${schoolYear.replace('/', '-')}-S${selectedSemester}-${selectedClass}-${safeSubject}-${safeType}-${safeMat}-${s.studentId}`;

        recordsToSave.push({
          gradeId: gradeId,
          studentId: s.studentId,
          studentName: s.name,
          nis: s.nis,
          nisn: s.nisn,
          class: selectedClass,
          subject: selectedSubject,
          assessmentType: selectedAssessmentType,
          material: materialScope,
          score: scoreVal,
          description: entry?.description || '',
          schoolYear: schoolYear,
          semester: selectedSemester,
          createdBy: user?.name || user?.email,
          updatedBy: user?.name || user?.email,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
          syncStatus: 'pending',
        });
      });

      // 1. Save to Firestore
      await saveBatchFirestoreGrades(recordsToSave);

      // 2. Audit Trail
      await logAuditEvent(
        user,
        'INPUT_NILAI',
        'Grades',
        `Kelas ${selectedClass} - ${selectedSubject}`,
        `Menyimpan nilai ${selectedAssessmentType} (${materialScope}) untuk ${recordsToSave.length} siswa`
      );

      // 3. Trigger async sync to Google Sheets
      syncGradesToSheets(selectedClass, selectedSubject).catch(e => {
        console.warn('Background Sheets sync error:', e);
      });

      showToast('success', 'Nilai Tersimpan', `Data nilai ${selectedSubject} berhasil disimpan.`);
    } catch (err: any) {
      showToast('error', 'Gagal Menyimpan Nilai', err.message);
    } finally {
      setSaving(false);
    }
  };

  const filteredStudents = students.filter(s =>
    s.name.toLowerCase().includes(searchTerm.toLowerCase()) ||
    s.nis.includes(searchTerm)
  );

  return (
    <div className="space-y-5">
      {/* Printable Header */}
      <div className="hidden print:block text-center border-b-2 border-black pb-3 mb-4">
        <h2 className="text-xl font-bold uppercase">{schoolProfile?.name || 'SD NEGERI 01 CEMARA INDAH'}</h2>
        <p className="text-xs">{schoolProfile?.address}</p>
        <p className="text-sm font-bold mt-2 uppercase">DAFTAR NILAI {selectedSubject.toUpperCase()}</p>
        <p className="text-xs">Kelas: {selectedClass} | Asesmen: {selectedAssessmentType} ({materialScope}) | Semester: {selectedSemester} ({schoolProfile?.academicYear})</p>
      </div>

      {/* Screen Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 print:hidden">
        <div>
          <h2 className="text-xl font-bold text-slate-800">Input Nilai Asesmen Siswa</h2>
          <p className="text-xs text-slate-500">
            Penilaian formatif, sumatif lingkup materi, STS, dan SAS (Skala 0–100)
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={handleAutoGenerateDescriptions}
            className="px-3 py-2 bg-indigo-50 text-indigo-700 border border-indigo-200 text-xs font-semibold rounded-xl hover:bg-indigo-100 transition flex items-center gap-1.5 shadow-2xs"
            title="Buat deskripsi capaian otomatis dari skor"
          >
            <Sparkles className="w-4 h-4 text-indigo-600" />
            <span>Deskripsi Otomatis</span>
          </button>

          <button
            type="button"
            onClick={() => window.print()}
            className="px-3 py-2 bg-white border border-slate-200 text-slate-700 text-xs font-semibold rounded-xl hover:bg-slate-50 transition flex items-center gap-1.5 shadow-2xs"
          >
            <Printer className="w-4 h-4 text-slate-600" />
            <span>Cetak A4</span>
          </button>

          <button
            type="button"
            onClick={handleSaveGrades}
            disabled={saving || students.length === 0}
            className="px-4 py-2 bg-school-navy text-white text-xs font-semibold rounded-xl hover:bg-school-blue transition flex items-center gap-1.5 shadow-sm disabled:opacity-50"
          >
            <Save className="w-4 h-4" />
            <span>{saving ? 'Menyimpan...' : 'Simpan Semua Nilai'}</span>
          </button>
        </div>
      </div>

      {/* Filter Parameters Card */}
      <div className="bg-white rounded-2xl border border-slate-200 p-4 shadow-xs space-y-4 print:hidden">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-5 gap-3">
          {/* Class */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">Kelas</label>
            <select
              value={selectedClass}
              onChange={e => setSelectedClass(e.target.value)}
              disabled={isTeacher && user?.assignedClasses.length === 1}
              className="w-full px-3 py-2 rounded-xl border border-slate-200 text-xs font-bold text-school-navy bg-white disabled:bg-slate-100"
            >
              <option value="1">Kelas 1</option>
              <option value="2">Kelas 2</option>
              <option value="3">Kelas 3</option>
              <option value="4">Kelas 4</option>
              <option value="5">Kelas 5</option>
              <option value="6">Kelas 6</option>
            </select>
          </div>

          {/* Subject */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">Mata Pelajaran</label>
            <select
              value={selectedSubject}
              onChange={e => setSelectedSubject(e.target.value)}
              className="w-full px-3 py-2 rounded-xl border border-slate-200 text-xs font-semibold bg-white"
            >
              {subjects.map(s => (
                <option key={s.id} value={s.name}>{s.name}</option>
              ))}
            </select>
          </div>

          {/* Assessment Type */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">Jenis Asesmen</label>
            <select
              value={selectedAssessmentType}
              onChange={e => setSelectedAssessmentType(e.target.value as AssessmentType)}
              className="w-full px-3 py-2 rounded-xl border border-slate-200 text-xs font-semibold bg-white"
            >
              <option value="Formatif">Formatif</option>
              <option value="Sumatif Lingkup Materi">Sumatif Lingkup Materi</option>
              <option value="Sumatif Tengah Semester">Sumatif Tengah Semester (STS)</option>
              <option value="Sumatif Akhir Semester">Sumatif Akhir Semester (SAS)</option>
            </select>
          </div>

          {/* Lingkup Materi */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">Lingkup Materi / Bab</label>
            <input
              type="text"
              value={materialScope}
              onChange={e => setMaterialScope(e.target.value)}
              placeholder="Contoh: Bab 1 Bilangan Cacah"
              className="w-full px-3 py-2 rounded-xl border border-slate-200 text-xs"
            />
          </div>

          {/* Semester */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">Semester</label>
            <select
              value={selectedSemester}
              onChange={e => setSelectedSemester(e.target.value as '1' | '2')}
              className="w-full px-3 py-2 rounded-xl border border-slate-200 text-xs font-semibold bg-white"
            >
              <option value="1">Semester 1 (Ganjil)</option>
              <option value="2">Semester 2 (Genap)</option>
            </select>
          </div>
        </div>

        <div className="flex items-center justify-between pt-2 border-t border-slate-100 text-xs text-slate-500">
          <div className="flex items-center gap-1.5">
            <AlertCircle className="w-4 h-4 text-slate-400" />
            <span>Skala nilai <strong>0–100</strong>. Nilai kosong tidak akan dianggap nol.</span>
          </div>

          <div className="relative min-w-[200px]">
            <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              value={searchTerm}
              onChange={e => setSearchTerm(e.target.value)}
              placeholder="Cari siswa..."
              className="w-full pl-9 pr-3 py-1.5 rounded-xl border border-slate-200 text-xs"
            />
          </div>
        </div>
      </div>

      {/* Grade Table */}
      <div className="bg-white rounded-2xl border border-slate-200 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse text-xs">
            <thead>
              <tr className="bg-slate-50 border-b border-slate-200 text-slate-600 font-bold uppercase tracking-wider text-[11px]">
                <th className="py-3 px-4 text-center w-12">No.</th>
                <th className="py-3 px-4 w-28">NIS</th>
                <th className="py-3 px-4 w-56">Nama Lengkap Siswa</th>
                <th className="py-3 px-4 text-center w-32">Nilai (0–100)</th>
                <th className="py-3 px-4">Deskripsi Capaian Kompetensi</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {loading ? (
                <tr>
                  <td colSpan={5} className="py-8 text-center text-slate-400">
                    Memuat data siswa dan nilai...
                  </td>
                </tr>
              ) : filteredStudents.length === 0 ? (
                <tr>
                  <td colSpan={5} className="py-10 text-center text-slate-400">
                    Tidak ada siswa aktif ditemukan di kelas {selectedClass}.
                  </td>
                </tr>
              ) : (
                filteredStudents.map((student, idx) => {
                  const entry = scoresMap[student.studentId] || { score: '', description: '' };
                  const scoreNum = entry.score !== '' ? Number(entry.score) : null;

                  return (
                    <tr key={student.studentId} className="hover:bg-slate-50/70 transition">
                      <td className="py-3 px-4 text-center font-medium text-slate-500">{idx + 1}</td>
                      <td className="py-3 px-4 font-mono font-medium text-slate-600">{student.nis || '-'}</td>
                      <td className="py-3 px-4 font-bold text-slate-800">{student.name}</td>

                      {/* Score Input */}
                      <td className="py-3 px-4 text-center">
                        <input
                          type="number"
                          min="0"
                          max="100"
                          value={entry.score}
                          onChange={e => handleScoreChange(student.studentId, e.target.value)}
                          placeholder="-"
                          className="w-20 px-3 py-1.5 rounded-xl border border-slate-300 text-center font-bold text-sm text-school-navy focus:ring-2 focus:ring-school-lightBlue focus:outline-hidden print:border-none"
                        />
                      </td>

                      {/* Description Input */}
                      <td className="py-3 px-4">
                        <textarea
                          rows={2}
                          value={entry.description}
                          onChange={e => handleDescriptionChange(student.studentId, e.target.value)}
                          placeholder="Deskripsi pencapaian kompetensi siswa..."
                          className="w-full px-3 py-1.5 rounded-xl border border-slate-200 text-xs focus:ring-1 focus:ring-school-lightBlue print:border-none print:p-0"
                        />
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Signature Area for Printing */}
      <div className="hidden print:grid grid-cols-2 gap-8 pt-8 mt-6 text-center text-xs">
        <div>
          <p>Mengetahui,</p>
          <p className="font-semibold">Kepala Sekolah</p>
          <div className="h-16" />
          <p className="font-bold underline">{schoolProfile?.principalName || 'Drs. H. Mulyadi, M.Pd.'}</p>
          <p>NIP. {schoolProfile?.principalNip || '-'}</p>
        </div>
        <div>
          <p>Kota Bandung, {formatDateIndo(new Date())}</p>
          <p className="font-semibold">Guru Pengampu Mata Pelajaran</p>
          <div className="h-16" />
          <p className="font-bold underline">{user?.name || 'Guru'}</p>
          <p>NIP. {user?.nip || '-'}</p>
        </div>
      </div>
    </div>
  );
};
